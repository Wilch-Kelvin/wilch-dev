// Copies real SKILL.md excerpts from Kelvin's skills4u checkout into
// src/content/skills4u.samples.ts, so the demo shows the actual files.
// Usage: node scripts/sync-skills.mjs [path-to-skills4u]   (default ~/Desktop/Skills)
import { readFile, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import { join } from 'node:path';

const root = process.argv[2] ?? join(homedir(), 'Desktop', 'Skills');
const plugins = [
  {
    id: 'ui-ux',
    plugin: 'ui-ux',
    skill: 'ui-ux-design',
    extras: '2 agents, 7 references, contrast.py, evals',
  },
  {
    id: 'docs',
    plugin: 'project-documentation',
    skill: 'project-documentation',
    extras: 'style.md, readme.md, word-document.md, evals',
  },
  {
    id: 'wiki',
    plugin: 'wiki-health',
    skill: 'wiki-health',
    extras: 'config.md, audit_wiki.py + tests, evals',
  },
  {
    id: 'inventory',
    plugin: 'inventory-auditor',
    skill: 'inventory-auditor',
    extras: 'schema.md, inventory.py + tests, evals',
  },
];
const BODY_LINES = 14;

function excerpt(text) {
  const lines = text.replace(/\r\n/g, '\n').split('\n');
  const end = lines.indexOf('---', 1);
  const front = lines.slice(0, end + 1);
  const body = lines.slice(end + 1);
  let cut = body.slice(0, BODY_LINES + 1);
  while (cut.length && cut.at(-1).trim() === '') cut.pop();
  return [...front, ...cut].join('\n');
}

const samples = [];
for (const p of plugins) {
  const path = `${p.plugin}/skills/${p.skill}/SKILL.md`;
  const source = excerpt(await readFile(join(root, path), 'utf8'));
  samples.push({ id: p.id, plugin: p.plugin, path, extras: p.extras, source });
}

const out = `// Generated by scripts/sync-skills.mjs from the skills4u repo. Do not edit by hand:
// change the SKILL.md files and run \`node scripts/sync-skills.mjs\` again.
import type { SkillSample } from './schema';

export const skillSamples: readonly SkillSample[] = ${JSON.stringify(samples, null, 2)};
`;
await writeFile('src/content/skills4u.samples.ts', out);
console.log(`Wrote ${samples.length} samples`);
