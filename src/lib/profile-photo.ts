// The hero portrait, hosted on Vercel Blob. Pure helpers only: the hero, the
// layout's preconnect and scripts/upload-profile.ts all share them.
// No "@/" imports here: Node runs the upload script straight from this file.

/** One encoded size of the photo. */
export type PhotoSource = { readonly url: `https://${string}`; readonly width: number };

export type ProfilePhoto = {
  /** Same picture at several widths (square, so height = width). */
  readonly sources: readonly PhotoSource[];
};

/** Public Vercel Blob stores all live under this host suffix. */
export const BLOB_HOST_SUFFIX = '.public.blob.vercel-storage.com';

export function isBlobUrl(url: string): boolean {
  try {
    const parsed = new URL(url);
    return parsed.protocol === 'https:' && parsed.hostname.endsWith(BLOB_HOST_SUFFIX);
  } catch {
    return false;
  }
}

function byWidth(sources: readonly PhotoSource[]): PhotoSource[] {
  return [...sources].sort((a, b) => a.width - b.width);
}

/** `srcset` value, smallest first: "…-400.webp 400w, …-800.webp 800w". */
export function photoSrcSet(sources: readonly PhotoSource[]): string {
  return byWidth(sources)
    .map((s) => `${s.url} ${s.width}w`)
    .join(', ');
}

/** The plain `src`: the largest file, for anything that ignores srcset. */
export function photoFallbackSrc(sources: readonly PhotoSource[]): string | null {
  return byWidth(sources).at(-1)?.url ?? null;
}

/**
 * The origin to preconnect to, so the TLS handshake with the Blob host starts
 * while the HTML is still parsing. Null if there's nothing to load or the
 * files don't share one host (a preconnect would then only help one of them).
 */
export function photoOrigin(photo: ProfilePhoto | null): string | null {
  if (!photo || photo.sources.length === 0) return null;
  const origins = new Set(photo.sources.map((s) => new URL(s.url).origin));
  return origins.size === 1 ? [...origins][0]! : null;
}

/**
 * True when an <img> has finished and got nothing. Checked after hydration
 * because an error that fires before React attaches `onError` is missed.
 */
export function imageFailed(img: { complete: boolean; naturalWidth: number }): boolean {
  return img.complete && img.naturalWidth === 0;
}

/** Source of src/content/profile-photo.ts, written by the upload script. */
export function profilePhotoModule(sources: readonly PhotoSource[]): string {
  const rows = byWidth(sources)
    .map((s) => `    { url: '${s.url}', width: ${s.width} },`)
    .join('\n');
  const value = sources.length ? `{\n  sources: [\n${rows}\n  ],\n}` : 'null';
  return [
    '// Generated by `node scripts/upload-profile.ts`. Do not edit by hand.',
    '// Null until the photo is uploaded; the hero then shows the K monogram.',
    "import type { ProfilePhoto } from '@/lib/profile-photo';",
    '',
    `export const profilePhoto: ProfilePhoto | null = ${value};`,
    '',
  ].join('\n');
}
