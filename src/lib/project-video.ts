// Hover-to-play demo videos on the project cards, hosted on Vercel Blob.
// Pure helpers only: the card, the tests and scripts/upload-videos.ts share
// them. No "@/" imports here: Node runs the upload script straight from this
// file.

export type BlobUrl = `https://${string}`;

export type ProjectVideo = {
  /** Silent, looping H.264 MP4 (plays in every browser). */
  readonly src: BlobUrl;
  /** Still frame shown until the video plays, and whenever it can't. */
  readonly poster: BlobUrl;
  readonly width: number;
  readonly height: number;
};

export type PlaybackState = {
  /** Pointer over the card, or keyboard focus inside it. */
  readonly engaged: boolean;
  /** Card mostly on screen (only used on touch screens, which can't hover). */
  readonly inView: boolean;
  /** `(hover: hover)`. Undefined until hydrated. */
  readonly canHover: boolean | undefined;
  /** `(prefers-reduced-motion: reduce)`. Undefined until hydrated. */
  readonly reducedMotion: boolean | undefined;
  /** The on-page pause button. */
  readonly paused: boolean;
};

/**
 * Should the card's video be playing right now?
 *
 * - Motion rules come first: a looping video is motion, so it only runs when
 *   the OS allows motion AND the on-page pause is off (WCAG 2.2.2). Unknown
 *   (before hydration) counts as "no", so nothing plays by accident.
 * - With a mouse, it plays on hover (or focus, for keyboard users).
 * - A phone has no hover, so there it plays while the card is on screen.
 */
export function shouldPlayVideo(state: PlaybackState): boolean {
  if (state.reducedMotion !== false || state.paused) return false;
  if (state.canHover === undefined) return false;
  return state.canHover ? state.engaged : state.inView;
}

/** Source of src/content/project-videos.ts, written by the upload script. */
export function projectVideosModule(videos: Readonly<Record<string, ProjectVideo>>): string {
  const rows = Object.entries(videos)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([id, v]) =>
      [
        `  ${id}: {`,
        `    src: '${v.src}',`,
        `    poster: '${v.poster}',`,
        `    width: ${v.width},`,
        `    height: ${v.height},`,
        '  },',
      ].join('\n'),
    );
  const body = rows.length ? `{\n${rows.join('\n')}\n}` : '{}';
  return [
    '// Generated by `node scripts/upload-videos.ts`. Do not edit by hand.',
    '// A project with no entry keeps its shape art.',
    "import type { ProjectId } from '@/content/schema';",
    "import type { ProjectVideo } from '@/lib/project-video';",
    '',
    `export const projectVideos: Partial<Record<ProjectId, ProjectVideo>> = ${body};`,
    '',
  ].join('\n');
}
